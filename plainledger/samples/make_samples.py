def wechat():
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\n')
    pad = lambda cells: cells + [''] * (11 - len(cells))
    for line in ['微信支付账单明细', '微信昵称：[示例用户]', '起始时间：[2026-08-01 00:00:00] 终止时间：[2026-08-31 23:59:59]',
                 '导出类型：[全部]', '导出时间：[2026-09-01 10:00:00]', '', f'共{len(WECHAT_ROWS)}笔记录',
                 '收入：3笔 367.00元', '支出：15笔 1462.10元', '中性交易：2笔 3000.00元', '注：',
                 '1. 充值/提现/理财通购买/零钱通存取/信用卡还款交易，将计入中性交易',
                 '2. 本明细仅展示当前账单中的交易，不包括已删除的记录',
                 '3. 本明细仅供个人对账使用',
                 '----------------------微信支付账单明细列表--------------------']:
        w.writerow(pad([line]))
    w.writerow(['交易时间', '交易类型', '交易对方', '商品', '收/支', '金额(元)', '支付方式', '当前状态', '交易单号', '商户单号', '备注'])
    for d, hh, mm, typ, cp, item, dirn, amt, method, status, oid, moid, note in WECHAT_ROWS:
        t = (START + dt.timedelta(days=d)).replace(hour=hh, minute=mm, second=random.randint(0, 59))
        w.writerow([t.strftime('%Y-%m-%d %H:%M:%S'), typ, cp, item, dirn, f'¥{amt:.2f}', method, status, oid + '\t', moid + ('\t' if moid != '/' else ''), note])
    data = buf.getvalue()
    with open(os.path.join(HERE, '微信支付账单(20260801-20260831).csv'), 'wb') as f:
        f.write(b'\xef\xbb\xbf' + data.encode('utf-8'))


